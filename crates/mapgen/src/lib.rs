    use super::*;

    /// A spec exercising every biome, settlement kind and layout on a medium map.
    fn busy(biome: Biome, seed: u64) -> MapSpec {
        let settlement = |size, kind, layout, position| SettlementSpec {
            kind: Some(kind),
            layout: Some(layout),
            position: Some(position),
            ..SettlementSpec::new(size)
        };
        MapSpec {
            seed: Some(seed),
            biome: Some(biome),
            size: Some(MapSize::Medium),
            settlements: vec![
                settlement(
                    SettlementSize::Town,
                    SettlementKind::Civilian,
                    SettlementLayout::Grid,
                    Position::Center,
                ),
                settlement(
                    SettlementSize::Village,
                    SettlementKind::Ruins,
                    SettlementLayout::Organic,
                    Position::Northwest,
                ),
                settlement(
                    SettlementSize::Village,
                    SettlementKind::Military,
                    SettlementLayout::Compound,
                    Position::Southeast,
                ),
                settlement(
                    SettlementSize::Hamlet,
                    SettlementKind::Civilian,
                    SettlementLayout::Scattered,
                    Position::Northeast,
                ),
            ],
            roads: Some(RoadSpec {
                through_roads: Some(2),
                width: Some(2),
                ..RoadSpec::default()
            }),
            ..MapSpec::default()
        }
    }

    #[test]
    fn every_biome_generates_a_valid_map() {
        for biome in Biome::ALL {
            let generated = generate(&busy(biome, 11)).unwrap();
            let map = &generated.map;
            assert_eq!((map.width, map.height), (50, 50));
            map.validate().unwrap();
            assert_eq!(generated.report.settlements.len(), 4, "{biome:?}");
            assert!(
                generated.report.settlements.iter().all(|s| s.buildings > 0),
                "{biome:?}: {:?}",
                generated.report.settlements
            );
            assert!(generated.report.coverage.road() > 0.0, "{biome:?}");
        }
    }

    /// Every biome, with every kind of settlement, writes a map file that loads with the same
    /// hexes and heights within a battlefield's limits.
    #[test]
    fn generated_maps_load() {
        let settlement = |size, kind| SettlementSpec {
            kind: Some(kind),
            walled: Some(true),
            ..SettlementSpec::new(size)
        };
        for biome in Biome::ALL {
            let spec = MapSpec {
                seed: Some(1),
                biome: Some(biome),
                size: Some(MapSize::Medium),
                fire: Some(Amount::Low),
                settlements: vec![
                    settlement(SettlementSize::City, SettlementKind::Civilian),
                    settlement(SettlementSize::Village, SettlementKind::Ruins),
                    settlement(SettlementSize::Hamlet, SettlementKind::Industrial),
                    settlement(SettlementSize::Outpost, SettlementKind::Military),
                ],
                roads: Some(RoadSpec {
                    width: Some(2),
                    through_roads: Some(2),
                    ..RoadSpec::default()
                }),
                ..MapSpec::default()
            };
            let generated = generate(&spec).unwrap();
            let map = MapAsset::parse(&generated.to_toml().unwrap())
                .unwrap_or_else(|error| panic!("{biome:?}: {error:#}"));
            assert_eq!(map, generated.map.to_asset().unwrap(), "{biome:?}");
            for (index, hex) in generated.map.hexes.iter().enumerate() {
                let (x, y) = generated.map.coordinate(index);
                let loaded = map.hex(x, y).unwrap();
                assert_eq!(loaded, *hex, "{biome:?} at {x},{y}");
                loaded
                    .validate()
                    .unwrap_or_else(|error| panic!("{biome:?} at {x},{y}: {error:#}"));
            }
        }
    }

    #[test]
    fn generation_is_deterministic() {
        let spec = busy(Biome::Temperate, 99);
        let first = generate(&spec).unwrap().to_toml().unwrap();
        assert_eq!(first, generate(&spec).unwrap().to_toml().unwrap());
        let other = generate(&busy(Biome::Temperate, 100)).unwrap();
        assert_ne!(first, other.to_toml().unwrap());
    }

