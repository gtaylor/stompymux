//! Procedural BattleTech battlefield generation for stompymux.
//!
//! Describe the battlefield with a [`MapSpec`] (biome, size, relief, how much water, woods and
//! rough ground, rivers, settlements and roads) and [`generate`] builds a [`HexMap`] that
//! [`GeneratedMap::to_toml`] writes in the stompymux map file format.
//!
//! The spec is plain serde data with a [JSON Schema](spec_schema), so the same description
//! can come from command-line flags, a JSON or TOML file, a map editor, or an LLM tool call.
//! Generation is deterministic: the same spec and seed always produce the same map, and the
//! resolved spec is embedded in the map file so it can be regenerated or tweaked later.
//!
//! ```
//! use stompymux_mapgen::{Biome, MapSize, MapSpec, SettlementSize, SettlementSpec, generate};
//!
//! let spec = MapSpec {
//!     seed: Some(7),
//!     biome: Some(Biome::Desert),
//!     size: Some(MapSize::Small),
//!     settlements: vec![SettlementSpec::new(SettlementSize::Village)],
//!     ..MapSpec::default()
//! };
//! let generated = generate(&spec).unwrap();
//! assert_eq!(generated.report.settlements.len(), 1);
//! let file = generated.to_toml().unwrap();
//! assert!(file.contains("terrain = '''"));
//! ```
//!
//! Generation runs in stages, each drawing from its own seeded random stream: elevation and
//! water, rivers, ground cover, settlements, roads, then fire and freezing.
//!
//! The map is made of `stompymux-map`'s layered [`Hex`]es, so it uses the same layers as the
//! game: [`Ground`] (clear, pavement, rough, ultra-rough peaks, rubble, sand, tundra, swamp),
//! [`Water`] with its [`Flow`], [`Foliage`] (woods, jungle and planted fields), road
//! [`Route`]s, [`Structure`]s (buildings, walls and bridges with a construction class) and
//! weather [`Condition`]s (deep and thin snow, and ice over frozen water).
