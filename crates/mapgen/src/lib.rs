/// The comment prefix that carries the resolved spec inside a generated map file.
const SPEC_COMMENT: &str = "# mapgen-spec: ";

/// A generated map with the resolved spec that reproduces it and a report of what was built.
#[derive(Debug, Clone)]
pub struct GeneratedMap {
    /// The spec with its seed and every default filled in.
    pub spec: MapSpec,
    pub map: HexMap,
    pub report: Report,
}

impl GeneratedMap {
    /// The map in the stompymux map file format, headed by a comment holding the resolved
    /// spec; see [`embedded_spec`].
    pub fn to_toml(&self) -> Result<String> {
        let file = embed_spec(&self.spec, &self.map.to_toml()?)?;
        Ok(format!(
            "# Generated by stompymux mapgen. The spec below regenerates this map exactly.\n{file}"
        ))
    }
}

/// `map_file` headed by a comment holding `spec`, which [`embedded_spec`] reads back. Map
/// editors use this to keep the spec a map was generated from when they save it.
pub fn embed_spec(spec: &MapSpec, map_file: &str) -> Result<String> {
    let spec = serde_json::to_string(spec)?;
    Ok(format!("{SPEC_COMMENT}{spec}\n{map_file}"))
}

/// The resolved spec embedded in a generated map file, or `None` for a map that was not
/// generated (or whose header was removed).
pub fn embedded_spec(map_file: &str) -> Option<Result<MapSpec>> {
    let line = map_file
        .lines()
        .find_map(|line| line.strip_prefix(SPEC_COMMENT))?;
    Some(serde_json::from_str(line).context("invalid embedded mapgen spec"))
}

/// Every setting generation runs with, resolved from the spec.
#[derive(Debug, Clone)]
pub(crate) struct Params {
    seed: u64,
    profile: biome::Profile,
    relief: Relief,
    water: Amount,
    woods: Amount,
    rough: Amount,
    fire: Amount,
    rivers: u8,
    connect_settlements: bool,
    through_roads: u8,
    road_width: u8,
}

/// Generate the battlefield `spec` describes.
pub fn generate(spec: &MapSpec) -> Result<GeneratedMap> {
    let spec = spec.resolve()?;
    // Resolution fills every field, so the expects below cannot fail.
    let roads = spec.roads.clone().expect("resolved");
    let environment = spec.environment.clone().expect("resolved");
    let biome = spec.biome.expect("resolved");
    let params = Params {
        seed: spec.seed.expect("resolved"),
        profile: biome::profile(biome),
        relief: spec.relief.expect("resolved"),
        water: spec.water.expect("resolved"),
        woods: spec.woods.expect("resolved"),
        rough: spec.rough.expect("resolved"),
        fire: spec.fire.expect("resolved"),
        rivers: spec.rivers.expect("resolved"),
        connect_settlements: roads.connect_settlements.expect("resolved"),
        through_roads: roads.through_roads.expect("resolved"),
        road_width: roads.width.expect("resolved"),
    };
    let (width, height) = spec.dimensions();
    let mut map = HexMap::new(width, height);
    map.gravity = environment.gravity.expect("resolved");
    map.temperature = environment.temperature.expect("resolved");
    map.flags = environment.flags.expect("resolved");
    let mut warnings = Vec::new();
    let elevation = terrain::elevation(&map, &params);
    terrain::shape(&mut map, &elevation, &params);
    let rivers = terrain::rivers(&mut map, &elevation, &params);
    terrain::cover(&mut map, &elevation, &params);
    let settlements = settlement::build_all(&mut map, &spec.settlements, &params, &mut warnings);
    let roads = roads::build(&mut map, &settlements, &params, &mut warnings);
    terrain::burn(&mut map, &elevation, &params);
    if spec.frozen.expect("resolved") {
        terrain::freeze(&mut map);
    }
    map.validate()?;
    let report = Report {
        seed: params.seed,
        biome,
        width,
        height,
        coverage: Coverage::of(&map),
        rivers,
        settlements: settlements.into_iter().map(|built| built.report).collect(),
        roads,
        fire_hexes: count_overlay(&map, DecorationKind::Fire),
        smoke_hexes: count_overlay(&map, DecorationKind::Smoke),
        warnings,
    };
    Ok(GeneratedMap { spec, map, report })
}

/// How many hexes carry `overlay`.
fn count_overlay(map: &HexMap, overlay: DecorationKind) -> usize {
    map.hexes
        .iter()
        .filter(|hex| hex.overlay() == Some(overlay))
        .count()
}

